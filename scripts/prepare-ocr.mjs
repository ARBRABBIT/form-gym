import { mkdirSync, readdirSync, copyFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const target = join(process.cwd(), 'public/ocr');
mkdirSync(join(target, 'core'), { recursive: true });
copyFileSync('node_modules/tesseract.js/dist/worker.min.js', join(target, 'worker.min.js'));
copyFileSync('node_modules/@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz', join(target, 'eng.traineddata.gz'));
for (const file of readdirSync('node_modules/tesseract.js-core')) if (file.endsWith('.wasm') || file.endsWith('.wasm.js')) copyFileSync(join('node_modules/tesseract.js-core', file), join(target, 'core', file));
copyFileSync('node_modules/tesseract.js-core/LICENSE', join(target, 'LICENSE'));
writeFileSync(join(target, 'NOTICE.txt'), 'Generated by scripts/prepare-ocr.mjs from the installed tesseract.js, tesseract.js-core and @tesseract.js-data/eng packages. OCR runs in the browser; images are not sent to an OCR server. See package licenses.\n');
